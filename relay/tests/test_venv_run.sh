#!/usr/bin/env bash
# test_venv_run.sh — bench for relay/scripts/venv-run.sh (pip/systemctl/runuser stubbed).
#
# The stub pip accepts ONLY the argvs venv-run.sh sends, and each of them was
# run once against a real pip (26.2.2, CPython 3.11 venvs, real uv-compiled
# locks) on 2026-11-01: sync from a VM-like state (17 drifts → 0, leftover
# packaging/setuptools/wheel removed), a lock with a wrong hash (pip refuses,
# freeze restored). The fake pip of 2026-10-31 accepted an argv the real one
# refused — an unexpected argv is therefore a failure here, never a pass.
#
# The healthy sync comes first: it is what the route meets on the VM, and a
# false FAILED there would teach us to ignore the verdict.
set -uo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
SCRIPT="$HERE/../scripts/venv-run.sh"
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
fail=0
ok()  { if [ "$1" = "$2" ]; then echo "  ok   $3"; else echo "  FAIL $3 (want=$1 got=$2)"; fail=1; fi }
has() { if printf '%s' "$2" | grep -- "$1" >/dev/null; then echo "  ok   $3"; else echo "  FAIL $3"; fail=1; fi }
hasnt() { if printf '%s' "$2" | grep -- "$1" >/dev/null; then echo "  FAIL $3"; fail=1; else echo "  ok   $3"; fi }

H64="$(printf '0%.0s' $(seq 64))"
lock() {  # name==version ... → a lock in the uv format (pin \, hash, via comment)
  local p
  echo "# This file was autogenerated by uv via the following command:"
  for p in "$@"; do printf '%s \\\n    --hash=sha256:%s\n    # via -r requirements.in\n' "$p" "$H64"; done
}

# One case = a fake root with two venvs whose pip is a stub. The stub runs
# under `env -i`, so its state path is baked into it, not passed by env.
setup() {  # $1 = case dir
  local c="$1" v
  mkdir -p "$c/locks" "$c/state"
  for v in wol-relay pock-sync; do
    lock fastapi==0.162.0 pydantic-core==2.50.2 pip==26.2.2 > "$c/locks/requirements-$v.lock"
    mkdir -p "$c/opt/$v/venv/bin" "$c/st/$v"
    # pip prints names as published (pydantic_core): the drift must normalise.
    printf 'fastapi==0.139.2\npydantic_core==2.50.2\npip==23.0.1\nsetuptools==66.1.1\n' > "$c/st/$v/installed"
    printf '#!/bin/sh\necho "Python 3.11.2"\n' > "$c/opt/$v/venv/bin/python"
    cat > "$c/opt/$v/venv/bin/pip" <<EOF
#!/usr/bin/env bash
S="$c/st/$v"
echo "\$*" >> "$c/calls"
case "\$*" in
  "list --format=freeze") cat "\$S/installed" ;;
  "install --require-hashes --no-deps --only-binary=:all: -r /dev/stdin")
    cat > "\$S/asked"; [ -e "\$S/pip-fails" ] && exit 1
    keep="\$(grep -i '^setuptools' "\$S/installed")"
    { grep -E '^[a-z].*==' "\$S/asked" | sed 's/ \\\\\$//'; [ -n "\$keep" ] && echo "\$keep"; } > "\$S/installed"
    [ -e "\$S/broken" ] && touch "\$S/broken-active"; true ;;
  "install --no-deps --only-binary=:all: -r /dev/stdin") cat > "\$S/installed"; rm -f "\$S/broken-active" ;;
  "uninstall -y "*) shift 2; for n in "\$@"; do grep -vi "^\$n==" "\$S/installed" > "\$S/x"; mv "\$S/x" "\$S/installed"; done ;;
  *) echo "unexpected pip argv: \$*" >&2; exit 99 ;;
esac
EOF
    chmod +x "$c/opt/$v/venv/bin/pip" "$c/opt/$v/venv/bin/python"
  done
  # runuser stub: records the user, refuses root, runs the rest.
  cat > "$c/as" <<EOF
#!/usr/bin/env bash
echo "as \$1" >> "$c/calls"
[ "\$1" = root ] && exit 98
shift; [ "\$1" = -- ] && shift; exec "\$@"
EOF
  # health: KO between a sync of a venv marked broken and its restore.
  cat > "$c/health" <<EOF
#!/usr/bin/env bash
case "\$*" in *8000*) v=wol-relay ;; *) v=pock-sync ;; esac
[ ! -e "$c/st/\$v/broken-active" ]
EOF
  printf '#!/bin/sh\necho "systemctl $*" >> "%s/calls"\n' "$c" > "$c/systemctl"
  printf '#!/bin/sh\necho "chown $*" >> "%s/calls"\n' "$c" > "$c/chown"
  chmod +x "$c/as" "$c/health" "$c/systemctl" "$c/chown"
  : > "$c/calls"
}

run() {  # $1 = case dir, $2 = mode
  local c="$1"
  VR_PREFIX="$c" VR_LOCKS="$c/locks" VR_LOG_DIR="$c/logs" VR_STATE_DIR="$c/state" \
    VR_AS_USER="$c/as" VR_CHOWN="$c/chown" VR_SYSTEMCTL="$c/systemctl" \
    VR_HEALTH="$c/health" VR_HEALTH_TRIES=2 VR_HEALTH_SLEEP=0 \
    bash "$SCRIPT" "$2" > "$c/stdout" 2>&1; RC=$?
  if [ "$2" = upgrade ]; then OUT="$(cat "$(ls -1t "$c"/logs/*.log | head -1)")"; else OUT="$(cat "$c/stdout")"; fi
  CALLS="$(cat "$c/calls")"
}

echo "case A — HEALTHY sync: both venvs DONE, extras removed"
setup "$TMP/a"; run "$TMP/a" upgrade
ok 0 "$RC" "exit 0"
has "VERDICT: DONE" "$OUT" "verdict DONE"
has "venvs: wol-relay=DONE pock-sync=DONE" "$OUT" "both venvs DONE"
has "before: fastapi==0.139.2" "$OUT" "records versions before"
has "after : fastapi==0.162.0" "$OUT" "records versions after"
has "removing (not in the lock): setuptools" "$OUT" "removes what the lock does not list"
hasnt "pydantic" "$(grep removing <<<"$OUT")" "a name spelled differently is not an extra (PEP 503)"
ok "" "$(grep -i setuptools "$TMP/a/st/wol-relay/installed")" "setuptools gone"
ok "$(cat "$TMP/a/locks/requirements-wol-relay.lock")" "$(cat "$TMP/a/st/wol-relay/asked")" "pip fed the lock, untouched"
has "systemctl restart wol-relay" "$CALLS" "restarts wol-relay"
has "systemctl restart pock-sync" "$CALLS" "restarts pock-sync"
has "chown pock:pock $TMP/a/opt/pock-sync/venv" "$CALLS" "pock venv handed to pock"
has "^as wol$" "$CALLS" "pip runs as wol"
has "^as pock$" "$CALLS" "pip runs as pock"
hasnt "^as root$" "$CALLS" "pip never runs as root"
hasnt "unexpected pip argv" "$OUT$(cat "$TMP/a/stdout")" "every pip argv is an expected one"

echo "case B — pip refuses the lock (hash mismatch): freeze restored, FAILED, other venv synced"
setup "$TMP/b"; touch "$TMP/b/st/wol-relay/pip-fails"; run "$TMP/b" upgrade
ok 1 "$RC" "exit 1"
has "venvs: wol-relay=FAILED pock-sync=DONE" "$OUT" "per-venv verdicts"
has "restoring the freeze" "$OUT" "says it restores"
ok "fastapi==0.139.2" "$(head -1 "$TMP/b/st/wol-relay/installed")" "wol-relay back on its old versions"

echo "case C — unhealthy after sync: ROLLED BACK, health OK again"
setup "$TMP/c"; touch "$TMP/c/st/pock-sync/broken"; run "$TMP/c" upgrade
ok 1 "$RC" "exit 1"
has "pock-sync=ROLLED-BACK" "$OUT" "pock-sync rolled back"
has "health after rollback: OK" "$OUT" "service healthy after rollback"
ok "fastapi==0.139.2" "$(head -1 "$TMP/c/st/pock-sync/installed")" "pock-sync on its old versions"
ok 2 "$(grep -c 'systemctl restart pock-sync' "$TMP/c/calls")" "restarted twice (sync + rollback)"

echo "case D — invalid lock: nothing installed, FAILED"
setup "$TMP/d"; printf -- '--index-url https://example.invalid/simple\n' >> "$TMP/d/locks/requirements-wol-relay.lock"
run "$TMP/d" upgrade
ok 1 "$RC" "exit 1"
has "wol-relay=FAILED" "$OUT" "wol-relay FAILED"
has "not a pin, hash or comment: --index-url" "$OUT" "names the offending line"
ok 1 "$(grep -c 'install --require-hashes' "$TMP/d/calls")" "pip install called once (pock-sync), never for the bad lock"
ok "fastapi==0.139.2" "$(head -1 "$TMP/d/st/wol-relay/installed")" "wol-relay untouched"

echo "case E — report: drift ⇒ exit 2, names normalised"
setup "$TMP/e"; run "$TMP/e" report
ok 2 "$RC" "exit 2"
has "fastapi: installed 0.139.2, lock 0.162.0" "$OUT" "lists the version drift"
has "setuptools: installed 66.1.1, not in the lock" "$OUT" "lists the extra"
hasnt "pydantic" "$OUT" "pydantic_core vs pydantic-core is not a drift"
has "Python 3.11.2" "$OUT" "shows the python version"
has "VERDICT: drift from the lock" "$OUT" "verdict"
hasnt "unexpected pip argv" "$OUT" "report uses an expected argv"

echo "case F — report: in sync ⇒ exit 0"
setup "$TMP/f"; for v in wol-relay pock-sync; do printf 'fastapi==0.162.0\npydantic_core==2.50.2\npip==26.2.2\n' > "$TMP/f/st/$v/installed"; done
run "$TMP/f" report
ok 0 "$RC" "exit 0"
has "VERDICT: in sync with the lock" "$OUT" "verdict"

echo "case G — report: lock missing ⇒ exit 3, never green"
setup "$TMP/g"; rm "$TMP/g/locks/requirements-pock-sync.lock"
for v in wol-relay pock-sync; do printf 'fastapi==0.162.0\npydantic_core==2.50.2\npip==26.2.2\n' > "$TMP/g/st/$v/installed"; done
run "$TMP/g" report
ok 3 "$RC" "exit 3"
has "could not measure" "$OUT" "verdict unmeasured"

echo "case H — lint: the grammar, positive and negative"
L="$TMP/l"; mkdir -p "$L"
lock fastapi==0.162.0 pip==26.2.2 > "$L/good"
lint() { bash "$SCRIPT" lint "$1" >/dev/null 2>&1; echo $?; }
ok 0 "$(lint "$L/good")" "uv-format lock accepted"
for real in "$HERE"/../scripts/requirements-*.lock; do
  ok 0 "$(lint "$real")" "versioned $(basename "$real") accepted"
done
printf 'fastapi==1.0\n' > "$L/nohash";                                    ok 1 "$(lint "$L/nohash")" "pin without hash refused"
{ cat "$L/good"; printf -- '-r /etc/shadow\n'; } > "$L/include";          ok 1 "$(lint "$L/include")" "include refused"
{ printf -- '--extra-index-url https://x\n'; cat "$L/good"; } > "$L/idx"; ok 1 "$(lint "$L/idx")" "index option refused"
{ cat "$L/good"; printf 'evil @ https://x/evil.whl \\\n    --hash=sha256:%s\n' "$H64"; } > "$L/url"; ok 1 "$(lint "$L/url")" "direct URL refused"
sed 's/sha256:0/sha256:/' "$L/good" > "$L/short";                         ok 1 "$(lint "$L/short")" "63-hex hash refused"
sed 's/^\(fastapi==0.162.0\) \\$/\1/' "$L/good" > "$L/open";              ok 1 "$(lint "$L/open")" "hash not attached to a pin refused"
: > "$L/empty";                                                           ok 1 "$(lint "$L/empty")" "empty lock refused"

echo "case I — unknown mode refused"
setup "$TMP/i"; run "$TMP/i" "upgrade --index-url x"
ok 64 "$RC" "exit 64"

[ "$fail" -eq 0 ] && echo "PASS" || { echo "FAILED"; exit 1; }
